import { describe, expect, it } from "vitest"

import { describeMangling, manglingIn, urlsIn } from "./mangling.js"

/**
 * The fixtures are the forms recorded in `FINDINGS.md`, not inventions.
 *
 * Six entries hold them, from four lanes: 5 November (#843), 8 November (#848),
 * 9 November evening (#848 again, where the comparison was first clean) and
 * 10 November evening (#854, the first with apostrophes in the run). The URLs
 * are shortened because length is what the entries argue about and is not what
 * this module reads — it reads the characters welded onto the link, and those
 * are reproduced exactly.
 */

const REPORT = "https://github.com/jam-overture/loom/blob/a-branch/reports/2026-11-09-a-report.md"
const RECORD = "https://github.com/jam-overture/loom/blob/a-branch/decisions/0375-a-record.md"

/**
 * The whole of it, on the body that is still stored on GitHub.
 *
 * #854's description was read back through the API on 11 November and these
 * are its two mangled lines, character for character — the run of four before
 * a record's bracket, the run of eight inside a report link's parentheses, and
 * the reversed run after each closing parenthesis. The two links in the same
 * body that came back clean are here too, because a check that found the right
 * four and also accused those would be no use to the run that reaches for it.
 */
describe("the body of #854, read back from the API", () => {
  const record =
    "https://github.com/jam-overture/loom/blob/framework-92-a-published-region-is-not-a-setting/decisions/" +
    "0379-a-file-may-publish-part-of-its-body-as-somebody-elses-code-and-a-check-that-reads-this-deployment-stops-at-the-marker.md"
  const report =
    "https://github.com/jam-overture/loom/blob/framework-92-a-published-region-is-not-a-setting/reports/" +
    "2026-11-10-framework-a-published-region-is-not-a-setting.md"

  const body = [
    "## Records and findings",
    "",
    "- **``''[0379](" + record + ")**,''`` `Accepted`, §1. Extends 0367, supersedes nothing.",
    "- **Numbering:** `main` holds up to 0377; **0371** is claimed by #834.",
    "- **Report:** [`reports/2026-11-10-framework-a-published-region-is-not-a-setting.md`](````''''" +
      report +
      "),''''```` with a diagram.",
    "",
    "---",
    "_Generated by [Claude Code](https://claude.ai/code/session_01LaQUpfTcbBg3i3gfcF13WC)_",
  ].join("\n")

  it("finds the four runs and nothing else", () => {
    expect(manglingIn(body)).toEqual([
      { url: record, line: 3, run: "``''", position: "before-label" },
      { url: record, line: 3, run: "''``", position: "after-link" },
      { url: report, line: 5, run: "````''''", position: "inside-parens" },
      { url: report, line: 5, run: "''''````", position: "after-link" },
    ])
  })

  it("counts the three URLs the body carries, the session link among them", () => {
    expect(urlsIn(body)).toEqual([record, report, "https://claude.ai/code/session_01LaQUpfTcbBg3i3gfcF13WC"])
  })
})

describe("the runs recorded on #848", () => {
  it("finds the pair that ate a report link and a record link in one body", () => {
    const body = ["**Report:** [`a-report.md`](``" + REPORT + ")``", "**Record:** [0375](```" + RECORD + "),```"].join("\n")

    expect(manglingIn(body)).toEqual([
      { url: REPORT, line: 1, run: "``", position: "inside-parens" },
      { url: REPORT, line: 1, run: "``", position: "after-link" },
      { url: RECORD, line: 2, run: "```", position: "inside-parens" },
      { url: RECORD, line: 2, run: "```", position: "after-link" },
    ])
  })

  it("reports each end of one link separately, because the two runs have been different lengths", () => {
    const body = "[0375](``" + RECORD + ")````"

    expect(manglingIn(body).map((mangling) => mangling.run)).toEqual(["``", "````"])
  })
})

describe("the run recorded on #854, which carried apostrophes", () => {
  it("finds a run welded on before the opening bracket", () => {
    const body = "**``''[0379](" + RECORD + ")"

    expect(manglingIn(body)).toEqual([{ url: RECORD, line: 1, run: "``''", position: "before-label" }])
  })

  it("finds a trailing run behind the emphasis and punctuation it was observed behind", () => {
    expect(manglingIn("[0379](" + RECORD + ")**,''")).toEqual([
      { url: RECORD, line: 1, run: "''", position: "after-link" },
    ])
    expect(manglingIn("[0379](" + RECORD + "),```")).toEqual([
      { url: RECORD, line: 1, run: "```", position: "after-link" },
    ])
  })
})

/**
 * The four thresholds, each in both directions.
 *
 * They are the whole of this module's judgement: a run of one against a bracket
 * is an ordinary code span beside an ordinary link and accusing it would make
 * this a check people learn to ignore, while a run of one inside the
 * parentheses cannot be anything else, because no URL begins with a backtick.
 */
describe("the line between a run that was inserted and a code span that was written", () => {
  it("flags a single character inside the parentheses, where nothing clean can sit", () => {
    expect(manglingIn("[0375](`" + RECORD + ")")).toEqual([
      { url: RECORD, line: 1, run: "`", position: "inside-parens" },
    ])
  })

  it("leaves a single character before the bracket, which is a code span ending at a link", () => {
    expect(manglingIn("`0375`[a record](" + RECORD + ")")).toEqual([])
  })

  it("flags two characters before the bracket, which is the form #854 arrived in", () => {
    expect(manglingIn("``[a record](" + RECORD + ")")).toEqual([
      { url: RECORD, line: 1, run: "``", position: "before-label" },
    ])
  })

  it("leaves a code span that starts a word after a link, because the space is the difference", () => {
    expect(manglingIn("[a record](" + RECORD + ") ``a span``")).toEqual([])
  })

  it("flags a run welded onto the closing parenthesis with no space", () => {
    expect(manglingIn("[a record](" + RECORD + ")``")).toEqual([
      { url: RECORD, line: 1, run: "``", position: "after-link" },
    ])
  })

  it("leaves one character welded onto the closing parenthesis, which is a code span opening", () => {
    expect(manglingIn("[a record](" + RECORD + ")`a span`")).toEqual([])
  })

  it("leaves a bare URL with a run on one side only", () => {
    expect(manglingIn("``" + REPORT)).toEqual([])
    expect(manglingIn(REPORT + "``")).toEqual([])
  })
})

describe("the bare URL recorded on #378", () => {
  it("finds a bare URL wrapped at both ends", () => {
    expect(manglingIn("``" + REPORT + "``")).toEqual([
      { url: REPORT, line: 1, run: "``", position: "around-bare-url" },
    ])
  })

  it("does not accuse a bare URL that merely follows a code span, because both ends are the evidence", () => {
    expect(manglingIn("`reports/a-report.md` " + REPORT)).toEqual([])
  })
})

describe("the forms that survived, which a check accusing them would be useless", () => {
  it.each([
    ["an autolink", "<" + REPORT + ">"],
    ["a bare URL on its own line", REPORT],
    ["a backticked repository path", "`reports/2026-11-09-a-report.md`"],
    ["a short markdown link", "[Claude Code](https://claude.ai/code/session_01LaQUpg)"],
    ["a single-backtick span holding a URL", "`" + REPORT + "`"],
    ["a markdown image", "![a figure](" + REPORT.replace(".md", ".webp") + ")"],
    ["a link followed by an ordinary code span", "[a report](" + REPORT + ") and `code` after it"],
  ])("leaves %s alone", (_form, body) => {
    expect(manglingIn(body)).toEqual([])
  })

  it("leaves a whole clean body alone", () => {
    const body = [
      "## The gate",
      "",
      "`pnpm install && pnpm verify` — **EXIT=0**.",
      "",
      "Paths rather than links, since a `decisions/` link does not survive the trip:",
      "",
      "- `decisions/0375-a-record.md`",
      "- `reports/2026-11-09-a-report.md`",
      "",
      "The preview:",
      "",
      "https://loom-git-a-branch.vercel.app",
    ].join("\n")

    expect(manglingIn(body)).toEqual([])
    expect(urlsIn(body)).toEqual(["https://loom-git-a-branch.vercel.app"])
  })
})

describe("a fenced block", () => {
  it("is not read, because a body reporting this defect quotes it", () => {
    const body = ["Here is what arrived:", "", "```", "[0375](``" + RECORD + ")``", "```", "", "and that is the whole of it."].join("\n")

    expect(manglingIn(body)).toEqual([])
    expect(urlsIn(body)).toEqual([])
  })

  it("does not swallow the rest of the body when it closes", () => {
    const body = ["```", "quoted", "```", "[0375](``" + RECORD + ")"].join("\n")

    expect(manglingIn(body)).toEqual([{ url: RECORD, line: 4, run: "``", position: "inside-parens" }])
  })

  it("is recognised when it is indented inside a list item", () => {
    const body = ["- an item:", "", "  ```", "  [0375](``" + RECORD + ")", "  ```"].join("\n")

    expect(manglingIn(body)).toEqual([])
  })
})

describe("what a run is told", () => {
  it("names the line, the characters and the URL, so the fix needs no search", () => {
    const [mangling] = manglingIn("\n[0375](``" + RECORD + ")")

    expect(mangling).toBeDefined()
    expect(describeMangling(mangling!)).toBe(
      `line 2: "\`\`" inside the parentheses, before the URL — ${RECORD}`
    )
  })

  it("counts every URL in the body, so a clean read says what it looked at", () => {
    const body = ["[a report](" + REPORT + ")", "<https://example.com/one>", "https://example.com/two"].join("\n")

    expect(urlsIn(body)).toEqual([REPORT, "https://example.com/one", "https://example.com/two"])
  })

  it("counts a mangled URL once, without the run around it", () => {
    expect(urlsIn("[0375](``" + RECORD + ")``")).toEqual([RECORD])
  })
})
